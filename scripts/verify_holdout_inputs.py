"""Check 3 for the joint freeze (ADR-0091, ADR-0097 item 9): verify the data the holdout path depends on, not only the
hashed code. Read-only; no holdout data is computed.

1. The freeze: if `provenance/HOLDOUT_FREEZE.txt` exists, `freeze.verify` (every hash and the environment block);
   before the freeze, the combined hash a freeze written now would record (the timestamp is not in the hash).
2. Raw inputs and reference prices: `provenance/CHECKSUMS.txt`, `data/reference/prices/MANIFEST.yaml`.
3. Downloaded references: Binance kline zips (`data/reference/binance/CHECKSUMS.txt`, under data/lake/_raw), aggTrades
   and the Hyperliquid funding / candles / user-funding MANIFEST.csv files. The 56 entries for the lake's aggTrades
   copies, deleted as redundant (action A0006, `decision/adr/RENUMBERING.md`; drift reads the verified zips,
   ADR-0003), are annotated as stale when missing; one that is present must still match.
4. Pre-Phase 4 outputs: `provenance/PRE_PHASE4_OUTPUT_CHECKSUMS.txt`. Its Phase 2 leader tables (`research/leader/`)
   were regenerated by the ADR-0069 gate 7 v2 rerun (P4-1, `make leader` at five origins, trial log 2026-11-23); an
   entry there that differs is annotated as superseded when the current file matches the output manifest.
5. The output manifest (`provenance/HOLDOUT_OUTPUT_MANIFEST.txt`): every file under the trees the holdout path reads
   matches, none is unlisted; the coverage gap left in no manifest; the shared inputs the tradable tree copied from
   the all-priced tree (`replay_tradable.SHARED`, and `PER_WINDOW` in each window), byte for byte.
6. The environment block (the freeze's).

Writes `research/audit/holdout_inputs_verification.md` and exits 1 on any problem.
Usage: POLARS_MAX_THREADS=8 uv run python scripts/verify_holdout_inputs.py
"""

import sys

sys.path.insert(0, "src")
import csv
import hashlib
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import yaml

from arkstream import freeze
from arkstream.config import load_context
from arkstream.replay_tradable import PER_WINDOW, SHARED

ROOT = Path(".").resolve()
OUT = ROOT / "research/audit"
STALE_LAKE_AGGTRADES = "data/lake/_raw/data/futures/um/daily/aggTrades/"
SUPERSEDED_LEADER = "research/leader/"


def sha(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 22), b""):
            h.update(chunk)
    return h.hexdigest()


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def check(entries: list["Entry"], superseded: dict[str, tuple[str, int]] | None = None
          ) -> tuple[int, list[str], list[str]]:
    """(path, expected sha256, expected bytes or None) -> (n ok, problems, stale or superseded entries annotated).

    `superseded`: the output manifest, for entries under `research/leader/` regenerated since (ADR-0097 item 8)."""
    def differs(p: Path, msg: str):
        r = rel(p)
        if superseded is not None and r.startswith(SUPERSEDED_LEADER) and r in superseded:
            digest, size = superseded[r]
            if freeze.size(p) == size and freeze.content_sha256(p) == digest:
                return "stale", f"superseded: {r}"
        return "bad", msg

    def one(e):
        p, want, size = e
        if not p.exists():
            kind = "stale" if rel(p).startswith(STALE_LAKE_AGGTRADES) else "missing"
            return kind, f"{kind}: {rel(p)}"
        if size is not None and p.stat().st_size != size:
            return differs(p, f"size differs: {rel(p)}")
        return ("ok", None) if sha(p) == want else differs(p, f"sha256 differs: {rel(p)}")
    with ThreadPoolExecutor(8) as ex:
        res = list(ex.map(one, entries))
    bad = [m for k, m in res if k in ("bad", "missing")]
    stale = [m for k, m in res if k == "stale"]
    return sum(k == "ok" for k, _ in res), bad, stale


Entry = tuple[Path, str, int | None]


def sums_file(path: str, base: Path = ROOT) -> list[Entry]:
    out: list[Entry] = []
    for line in (ROOT / path).read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split()
        out.append((base / parts[2], parts[0], int(parts[1])))
    return out


def manifest_csv(path: str, base: str) -> list[Entry]:
    with open(ROOT / path, encoding="utf-8", newline="") as fh:
        return [(ROOT / base / r["file"], r["sha256"], int(r["bytes"])) for r in csv.DictReader(fh)]


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    ctx = load_context()
    report = ["# Holdout input verification (Check 3; ADR-0091, ADR-0097 item 9)", ""]
    failures: list[str] = []
    listed: set[str] = set()

    # 1. freeze
    report.append("## 1. Freeze")
    if (ROOT / freeze.FREEZE_FILE).exists():
        recorded, env, h = freeze.read_freeze(ROOT)
        try:
            freeze.verify(ctx)
            report += [f"- `{freeze.FREEZE_FILE}`: freeze_hash `{h}` over {len(recorded)} files and "
                       f"{len(env)} environment lines", "- matches: **True**"]
        except freeze.FreezeError as e:
            report += [f"- `{freeze.FREEZE_FILE}`: freeze_hash `{h}`", f"- matches: **False**: {e}"]
            failures.append("freeze")
    else:
        lines, env = freeze.digest_lines(ROOT), freeze.env_lines(ROOT)
        report += [f"- no `{freeze.FREEZE_FILE}` yet (P5-7 writes it)",
                   f"- a freeze written now would record freeze_hash `{freeze.combined(lines + env)}` over "
                   f"{len(lines)} files and {len(env)} environment lines"]
    paths = freeze.frozen_paths(ROOT)
    listed |= set(paths)
    report.append(f"- frozen set: {len(paths)} files: "
                  f"{sum(p.startswith('src/') for p in paths)} sources, "
                  f"{sum(p.startswith('decision/') for p in paths)} documents, "
                  f"{sum(p.startswith('config/') for p in paths)} config files, "
                  f"{len(freeze.MANIFEST_FILES)} manifests, the shortlist `{freeze.SHORTLIST}`")

    # 2-4. manifests
    groups: dict[str, list[Entry]] = {
        "raw inputs and reference prices (provenance/CHECKSUMS.txt)": sums_file("provenance/CHECKSUMS.txt"),
        "reference prices (data/reference/prices/MANIFEST.yaml)": [
            (ROOT / "data/reference/prices" / f["path"], f["sha256"], int(f["bytes"]))
            for f in yaml.safe_load(
                (ROOT / "data/reference/prices/MANIFEST.yaml").read_text(encoding="utf-8"))["files"]],
        "Binance kline zips (data/reference/binance/CHECKSUMS.txt)": sums_file(
            "data/reference/binance/CHECKSUMS.txt", ROOT / "data/lake/_raw"),
        "Binance aggTrades (MANIFEST.csv)": manifest_csv("data/reference/binance/aggtrades/MANIFEST.csv",
                                                         "data/reference/binance/aggtrades"),
        "Hyperliquid funding (MANIFEST.csv)": manifest_csv("data/reference/hyperliquid/funding/MANIFEST.csv",
                                                           "data/reference/hyperliquid"),
        "Hyperliquid 4h candles (MANIFEST.csv)": manifest_csv("data/reference/hyperliquid/candles_4h/MANIFEST.csv",
                                                              "data/reference/hyperliquid"),
        "Hyperliquid user funding (MANIFEST.csv)": manifest_csv(
            "data/reference/hyperliquid/user_funding/MANIFEST.csv", "data/reference/hyperliquid"),
        "pre-Phase 4 outputs (provenance/PRE_PHASE4_OUTPUT_CHECKSUMS.txt)": sums_file(
            "provenance/PRE_PHASE4_OUTPUT_CHECKSUMS.txt"),
    }
    outputs = freeze.read_output_manifest(ROOT) if (ROOT / freeze.OUTPUT_MANIFEST).exists() else {}
    report += ["", "## 2-4. Data manifests", "| Manifest | Files | OK | Stale or superseded (annotated) | Problems |",
               "| --- | ---: | ---: | ---: | --- |"]
    for name, entries in groups.items():
        ok, bad, stale = check(entries, outputs if name.startswith("pre-Phase 4") else None)
        problems = "; ".join(bad[:5]) + (" ..." if len(bad) > 5 else "") or "none"
        report.append(f"| {name} | {len(entries)} | {ok} | {len(stale)} | {problems} |")
        if bad:
            failures.append(name)
        for p, _, _ in entries:
            try:
                listed.add(rel(p))
            except ValueError:
                pass
        print(name, len(entries), ok, len(stale), len(bad), flush=True)
    report += ["", f"Stale entries are the lake's aggTrades copies under `{STALE_LAKE_AGGTRADES}`, deleted as "
               "redundant (action A0006, `decision/adr/RENUMBERING.md`); drift reads the verified zips in "
               "`data/reference/binance/aggtrades` (ADR-0003). Superseded entries are pre-Phase 4 Phase 2 leader "
               "tables regenerated by the ADR-0069 gate 7 v2 rerun (P4-1, trial log 2026-11-23); each current file "
               "matches the output manifest. The manifests themselves are not edited (ADR-0097 item 8)."]

    # 5. output manifest, coverage gap, shared inputs
    out_problems = freeze.check_output_manifest(ROOT)
    want = outputs
    listed |= set(want)
    trees = freeze.tree_files(ROOT)
    gap = [f for f in trees if f not in listed]
    by_tree = {t: sum(f.startswith(t + "/") for f in trees) for t in freeze.OUTPUT_TREES}
    report += ["", "## 5. Output manifest and coverage",
               f"- `{freeze.OUTPUT_MANIFEST}`: {len(want)} files listed; problems: **{len(out_problems)}**"
               + ("".join(f"\n  - {p}" for p in out_problems[:20])),
               f"- files under the output trees: {len(trees)} ({by_tree})",
               f"- in no manifest: **{len(gap)}**" + "".join(f"\n  - `{g}`" for g in gap[:20])]
    if out_problems:
        failures.append("output manifest")
    if gap:
        failures.append("coverage gap")
    tradable = ROOT / ctx.raw["selection_v2"]["tradable_dir"]
    allpriced = ROOT / "research/replay_allpriced"
    pairs = [(tradable / n, allpriced / n) for n in SHARED]
    for w in sorted(tradable.glob("origin=*/window=*")):
        pairs += [(w / n, allpriced / w.relative_to(tradable) / n) for n in PER_WINDOW if (w / n).exists()]
    differ = [rel(a) for a, b in pairs if not b.exists() or sha(a) != sha(b)]
    report.append(f"- shared inputs of the tradable tree identical to the all-priced tree: {len(pairs) - len(differ)} "
                  f"of {len(pairs)}" + "".join(f"\n  - differs: `{d}`" for d in differ[:20]))
    if differ:
        failures.append("shared inputs")

    # 6. environment
    report += ["", "## 6. Environment (the freeze's environment block)"]
    report += [f"- {k}: `{v}`" for k, v in freeze.environment(ROOT)]
    report += [f"- config cutoff `{ctx.raw['cutoff']}`", "",
               f"**Result: {'PASS' if not failures else 'FAIL: ' + ', '.join(failures)}**"]
    (OUT / "holdout_inputs_verification.md").write_text("\n".join(report) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(report))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
